-- Adopt snake_case for COLUMN names, finishing what 0004 started on tables.
--
-- After this the whole database reads in one casing: snake_case tables,
-- snake_case columns, snake_case enum types, snake_case indexes. No identifier
-- anywhere needs double-quoting to be typed by hand.
--
--   * 2090 columns      -- "userId"    -> "user_id"
--   *  342 constraints  -- names embed column names, so they move too
--   *  611 indexes      -- "idx_session_userId" -> "idx_session_user_id"
--
-- No application code changes with this migration. In Drizzle the physical name
-- is the string argument, and the TypeScript property is the key -- this is a
-- change from `userId: text("userId")` to `userId: text("user_id")`, so every
-- `.userId` reference in the app keeps working untouched. The one place that had
-- hardcoded a physical column name in raw SQL (a `sql`"userId" = ...`` predicate
-- in the resume hub stats) was rewritten to use eq() with the column reference
-- first, so nothing is left depending on the old spelling.
--
-- Renaming a column automatically carries its indexes, constraints and defaults
-- with it -- Postgres tracks those by column number, not by name. What it does
-- NOT do is rename the constraint and index OBJECTS, whose names still spell out
-- the old column. Steps 2 and 3 fix that, which is why the FK names below stop
-- being hybrids: "user_skill_userId_user_id_fk" finally becomes
-- "user_skill_user_id_user_id_fk".
--
-- Every pair is derived from the Drizzle snapshot, not from pattern matching, and
-- every rename is guarded so this is safe to re-run. One DO block, so Postgres
-- applies it atomically.
DO $$
DECLARE
    r       record;
    newname text;
BEGIN
    ---------------------------------------------------------------------------
    -- 4. Catch-all: any constraint still not snake_case.
    --
    --    A handful of names were already clipped to 63 bytes by an earlier
    --    migration, so they no longer match EITHER spelling in _con above and
    --    step 2 skips them -- they would keep a camelCase name forever. Rather
    --    than chase historical spellings, this rebuilds the name that Drizzle
    --    would derive, straight from the catalog: table, columns, and (for a
    --    foreign key) the referenced table and columns. By this point steps 1-3
    --    have already renamed all of those, so the result is correct regardless
    --    of what the constraint was called before.
    ---------------------------------------------------------------------------
    FOR r IN
        SELECT con.conname, con.conrelid, con.contype, t.relname AS tbl,
               ft.relname AS ftbl,
               (SELECT string_agg(a.attname, '_' ORDER BY k.ord)
                  FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = con.conrelid
                                     AND a.attnum = k.attnum) AS cols,
               (SELECT string_agg(a.attname, '_' ORDER BY k.ord)
                  FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = con.confrelid
                                     AND a.attnum = k.attnum) AS fcols
        FROM pg_constraint con
        JOIN pg_class t     ON t.oid = con.conrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace AND n.nspname = 'public'
        LEFT JOIN pg_class ft ON ft.oid = con.confrelid
        WHERE con.contype IN ('f', 'u', 'p')
          AND con.conname !~ '^[a-z][a-z0-9_]*$'
    LOOP
        newname := CASE r.contype
            WHEN 'f' THEN format('%s_%s_%s_%s_fk', r.tbl, r.cols, r.ftbl, r.fcols)
            WHEN 'u' THEN format('%s_%s_unique', r.tbl, r.cols)
            ELSE format('%s_pkey', r.tbl)
        END;

        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint c2
            WHERE c2.conrelid = r.conrelid AND c2.conname = left(newname, 63)
        ) THEN
            EXECUTE format('ALTER TABLE public.%I RENAME CONSTRAINT %I TO %I',
                           r.tbl, r.conname, newname);
        END IF;
    END LOOP;

