        JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
        WHERE NOT EXISTS (
            SELECT 1 FROM pg_class c2
            JOIN pg_namespace n2 ON n2.oid = c2.relnamespace
            WHERE n2.nspname = 'public' AND c2.relname = m.new_name)
    LOOP
        EXECUTE format('ALTER TABLE public.%I RENAME TO %I', r.old_name, r.new_name);
    END LOOP;

    ---------------------------------------------------------------------------
    -- 2. Constraints -- keyed on the NEW table name, since step 1 already ran.
    ---------------------------------------------------------------------------
    FOR r IN
        SELECT m.tbl, m.old_name, m.new_name FROM _c m
        JOIN pg_class t      ON t.relname = m.tbl AND t.relkind = 'r'
        JOIN pg_namespace n  ON n.oid = t.relnamespace AND n.nspname = 'public'
        JOIN pg_constraint c ON c.conrelid = t.oid AND c.conname = m.old_name
        WHERE NOT EXISTS (
            SELECT 1 FROM pg_constraint c2
            WHERE c2.conrelid = t.oid AND c2.conname = m.new_name)
    LOOP
        EXECUTE format('ALTER TABLE public.%I RENAME CONSTRAINT %I TO %I',
                       r.tbl, r.old_name, r.new_name);
    END LOOP;

