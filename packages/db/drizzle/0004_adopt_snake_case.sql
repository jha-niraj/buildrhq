-- Adopt snake_case for every physical name in the database.
--
-- Migration 0002 moved tables from PascalCase to camelCase. This finishes the
-- job and moves them to snake_case, which is the Postgres convention and the
-- only casing that does not require double-quoting every identifier by hand:
-- Postgres folds unquoted identifiers to lower case, so `select * from
-- user_achievement` just works, where "userAchievement" always needed quotes.
--
-- 0002 is deliberately left in place rather than rewritten. It has already been
-- applied to real databases, and rewriting an applied migration would strand
-- any environment sitting on camelCase with no path forward. Replaying from
-- scratch gives PascalCase -> camelCase -> snake_case, which is one extra hop
-- and always lands in the same place.
--
-- Covered here:
--   * 186 tables    -- "userAchievement" -> "user_achievement"
--   * 135 enum types -- "ActivityType"    -> "activity_type"
--   * 516 constraints (primary keys, uniques, foreign keys)
--
-- COLUMN names are intentionally NOT touched. They are still camelCase
-- ("userId", "createdAt"), which is why the constraint names below read as
-- hybrids -- "user_skill_userId_user_id_fk" is the table part renamed and the
-- column part left alone. That is exactly the name Drizzle derives from the
-- current schema, so the snapshot and the database agree. Renaming columns is a
-- separate, much larger change and belongs in its own migration.
--
-- Every rename is derived from the Drizzle snapshot rather than by pattern
-- matching on names, so a column that happens to share a table's name cannot be
-- rewritten by accident. Each is guarded (rename only when the old name exists
-- and the new one is free), making this safe to re-run and safe against a
-- partially-renamed database. The whole thing is one DO block, which Postgres
-- runs as a single statement: it either fully applies or fully rolls back.
